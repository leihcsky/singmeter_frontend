/**
 * Build-time generator: lightweight blog catalog + per-article lazy loaders.
 * Parses article meta from source (no JSX runtime needed in Node).
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { enrichBlogMeta } from '../src/data/blogAuthors.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const articlesDir = path.join(root, 'src/blog/articles');
const blogDir = path.join(root, 'src/blog');

function readLegacySlugOrder() {
  const legacyPath = path.join(blogDir, 'index.legacy-order.json');
  if (fs.existsSync(legacyPath)) {
    return JSON.parse(fs.readFileSync(legacyPath, 'utf8'));
  }
  return [];
}

/** Extract `const meta = { ... };` as a JS object via Function (build-time only). */
function parseMetaFromSource(source) {
  const match = source.match(/const meta = (\{[\s\S]*?\n\});/);
  if (!match) return null;
  try {
    // eslint-disable-next-line no-new-func
    return new Function(`return (${match[1]});`)();
  } catch (err) {
    console.warn('[gen:blog] failed to parse meta block:', err.message);
    return null;
  }
}

const files = fs.readdirSync(articlesDir).filter((f) => f.endsWith('Article.jsx'));
const bySlug = new Map();

for (const file of files) {
  const source = fs.readFileSync(path.join(articlesDir, file), 'utf8');
  const rawMeta = parseMetaFromSource(source);
  if (!rawMeta?.slug) {
    console.warn(`[gen:blog] skip ${file}: missing meta.slug`);
    continue;
  }
  const importPath = `./articles/${file.replace(/\.jsx$/, '')}`;
  bySlug.set(rawMeta.slug, {
    meta: enrichBlogMeta(rawMeta),
    importPath,
    file,
  });
}

const legacyOrder = readLegacySlugOrder();
const orderedSlugs = legacyOrder.length
  ? [
      ...legacyOrder.filter((s) => bySlug.has(s)),
      ...[...bySlug.keys()].filter((s) => !legacyOrder.includes(s)).sort(),
    ]
  : [...bySlug.keys()].sort();

const catalog = orderedSlugs.map((slug) => bySlug.get(slug).meta);
const loaderEntries = orderedSlugs.map(
  (slug) => `  '${slug}': () => import('${bySlug.get(slug).importPath}'),`,
);

fs.writeFileSync(
  path.join(blogDir, 'catalog.generated.js'),
  `// AUTO-GENERATED by scripts/generate-blog-catalog.mjs — do not edit manually.\nexport const blogCatalog = ${JSON.stringify(catalog, null, 2)};\n`,
  'utf8',
);

fs.writeFileSync(
  path.join(blogDir, 'articleLoaders.js'),
  `// AUTO-GENERATED by scripts/generate-blog-catalog.mjs — do not edit manually.
import { enrichBlogMeta } from '../data/blogAuthors.js';
import { blogCatalog } from './catalog.generated.js';

const articleLoaders = {
${loaderEntries.join('\n')}
};

export function getBlogCatalogEntry(slug) {
  return blogCatalog.find((a) => a.slug === slug) ?? null;
}

export async function loadBlogArticle(slug) {
  const loader = articleLoaders[slug];
  if (!loader) return null;
  const mod = await loader();
  const Component = mod.default;
  if (!Component?.meta) return null;
  return { ...enrichBlogMeta(Component.meta), component: Component };
}
`,
  'utf8',
);

console.log(`[gen:blog] ${catalog.length} articles → catalog.generated.js, articleLoaders.js`);
